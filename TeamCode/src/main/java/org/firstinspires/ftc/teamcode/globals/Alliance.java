package org.firstinspires.ftc.teamcode.globals;

/**
 * Which alliance the robot is playing for.
 *
 * <p>Field geometry is authored for {@link #BLUE}. {@link #RED} is its mirror image across the
 * field's vertical centerline — the same transform the Pedro visualizer's mirror option applies
 * when exporting red paths, so paths and aiming always agree.
 */
public enum Alliance {
    BLUE,
    RED
}
